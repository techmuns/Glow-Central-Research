// data/tracked-universe.js — the broad market universe the FILINGS feeds track.
//
//   prime(payload)       seeded from tracked-universe.json at bootstrap (deferred)
//   all()                every tracked company, { ticker, name, marketCapCr }, BIGGEST FIRST
//   marketCapOf(ticker)  a company's market cap in ₹Cr, or null if it is not in the universe
//   meta()               count, floor and provenance
//
// WHY THIS IS NOT coverage.js AND NOT universe.js. `coverage` is the family's book (what "Portfolio"
// means). `universe.js` is the NSE-500 the technicals model was built for. This is a third thing: the
// ~1,900-company list, every listed company above a market-cap floor, that Corporate Announcements
// and Insider Trades walk — because a filing is worth tracking for any company, not just an index
// member. It is ORDERED BY MARKET CAP so a bounded walk covers the biggest names first, which is the
// priority the reader asked for. Generated by scripts/import-tracked-universe.mjs from a committed
// Screener export; see docs/DATA-CONTRACTS.md.

import { revalidatedJson } from '../core/store.js';

let raw = null;
let mcapByTicker = null;
let loading = null;

export function prime(payload) {
  if (payload && Array.isArray(payload.companies)) {
    raw = payload;
    mcapByTicker = null; // rebuilt lazily against the new list
  }
  return isLoaded();
}

/**
 * Fetch and prime the universe if the bootstrap has not already. Idempotent, and the fetch is shared
 * per path by `revalidatedJson`, so a filings tab awaiting this and the deferred bootstrap pass do
 * not double-download it. Resolves to `raw` (or null if it could not be read — the caller falls back
 * to the book).
 */
export function load() {
  if (isLoaded()) return Promise.resolve(raw);
  if (!loading) {
    loading = revalidatedJson('data/tracked-universe.json')
      .then((payload) => {
        prime(payload);
        return raw;
      })
      .catch(() => null);
  }
  return loading;
}

export const isLoaded = () => !!raw;

/** Every tracked company, biggest market cap first — the walk order. */
export const all = () => (raw ? raw.companies : []);

/** A company's market cap in ₹Cr, or null. Used to order the book by size in Portfolio scope. */
export function marketCapOf(ticker) {
  if (!mcapByTicker) mcapByTicker = new Map(all().map((c) => [c.ticker.toUpperCase(), c.marketCapCr]));
  return mcapByTicker.get(String(ticker || '').toUpperCase()) ?? null;
}

export function meta() {
  return {
    count: raw?.count ?? all().length,
    floorCr: raw?.floorCr ?? null,
    generatedAt: raw?.generatedAt ?? null,
    source: raw?.source ?? null,
  };
}
